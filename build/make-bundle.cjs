// Accurivo single-file bundle maker: inlines db.js, crypto.js, server.js and
// the whole public/ folder into ONE .cjs file with no readable source strings.
// Run: node build/make-bundle.cjs
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const PUB = path.join(ROOT, 'public');
const OUT = path.join(__dirname, 'accurivo-bundle.cjs');

const files = {
  db: fs.readFileSync(path.join(ROOT, 'db.js'), 'utf8'),
  crypto: fs.readFileSync(path.join(ROOT, 'crypto.js'), 'utf8'),
  server: fs.readFileSync(path.join(ROOT, 'server.js'), 'utf8'),
};
const embed = {};
for (const f of fs.readdirSync(PUB)) {
  embed[f] = fs.readFileSync(path.join(PUB, f)).toString('base64');
}

// inner program: a tiny module registry; './db' and './crypto' resolve to the
// inlined modules, everything else goes to the real require.
const inner = `
(function () {
  'use strict';
  var realRequire = require;
  var path = realRequire('path');
  var mods = {};
  var defs = {
    db: MODULE_DB,
    crypto: MODULE_CRYPTO,
    server: MODULE_SERVER,
  };
  function req(name) {
    if (name === './db') return mods.db.exports;
    if (name === './crypto') return mods.crypto.exports;
    return realRequire(name);
  }
  globalThis.ACCURIVO_EMBED = EMBED_JSON;
  var dn = path.dirname(process.execPath);
  for (var k of ['db', 'crypto', 'server']) {
    var m = { exports: {} };
    mods[k] = m;
    defs[k](m, m.exports, req, dn, m);
  }
})();
`;

const wrap = (src) => 'function (module, exports, require, __dirname) {\n' + src + '\n}';
let prog = inner
  .replace('MODULE_DB', wrap(files.db))
  .replace('MODULE_CRYPTO', wrap(files.crypto))
  .replace('MODULE_SERVER', wrap(files.server))
  .replace('EMBED_JSON', JSON.stringify(embed));

// hide all source: ship it base64-encoded inside a Function constructor call
const b64 = Buffer.from(prog, 'utf8').toString('base64');
const out = [
  '// Accurivo single-file build — generated by build/make-bundle.cjs',
  "'use strict';",
  'var __b64 = "' + b64 + '";',
  'var __src = Buffer.from(__b64, "base64").toString("utf8");',
  'var __f = new Function("globalThis", "require", __src);',
  '__f(globalThis, require);',
  '// ' + Buffer.from('accurivo-build-' + Date.now()).toString('base64'),
  '',
].join('\n');
fs.writeFileSync(OUT, out);
console.log('bundle written: ' + OUT + ' (' + Math.round(out.length / 1024) + ' KB)');
